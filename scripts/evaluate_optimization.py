"""Evaluate inverse-model software recovery and the Run 5 schedule.

Manifest-color recovery is an internal consistency test because those RGB
values were generated by the same empirical model. Rendered-frame recovery
adds the digital twin's glass, lighting, and material appearance, but still is
not physical carryover validation.
"""

import json
from itertools import pairwise
from pathlib import Path

import cv2
import numpy as np
import pandas as pd

from changeover_guard.carryover import (
    CarryoverConfig,
    estimate_carryover,
)
from changeover_guard.contracts import Recipe, delta_e
from changeover_guard.costs import build_transition_matrix
from changeover_guard.dataset import vial_labels
from changeover_guard.features import extract_vial_features
from changeover_guard.optimizer import greedy_sequence, optimize_sequence
from changeover_guard.sensitivity import analyze_sensitivity

ROOT = Path(__file__).parents[1]
VIDEO_OFFSETS_S = (-0.6, -0.45, -0.3)


def _measure_video_end(cap: cv2.VideoCapture, end_s: float) -> tuple[float, ...]:
    colors = []
    for offset in VIDEO_OFFSETS_S:
        cap.set(cv2.CAP_PROP_POS_MSEC, (end_s + offset) * 1000)
        ok, image = cap.read()
        if not ok:
            raise RuntimeError(f"no video frame at {end_s + offset:.2f} s")
        colors.append(extract_vial_features(image).rgb_median)
    return tuple(float(value) for value in np.median(colors, axis=0))


def _recipe(row: pd.Series) -> Recipe:
    ml = {
        tank: float(row[column])
        for tank, column in (
            ("T100", "t100_ml"),
            ("T200", "t200_ml"),
            ("T400", "t400_ml"),
        )
        if pd.notna(row[column])
    }
    return Recipe(int(row.recipe_id), ml)


def _synthetic_recovery() -> dict:
    manifest = pd.read_csv(ROOT / "synthetic" / "manifest.csv")
    catalog = {
        int(row.recipe_id): _recipe(row)
        for _, row in manifest.drop_duplicates("recipe_id").iterrows()
    }
    labels = pd.read_csv(
        ROOT / "synthetic" / "vial_fill" / "labels" / "video100_frame_labels.csv"
    )
    full_frames = (
        labels[labels.in_fill == 1]
        .groupby("vial", sort=False)
        .tail(1)
        .set_index("vial")
    )
    config = CarryoverConfig(residual_model="bulk", max_fraction=0.30, grid_step=0.001)
    manifest_errors = []
    render_errors = []
    render_fit = []
    for _, row in manifest.iterrows():
        if pd.isna(row.prev_recipe_id) or float(row.carry_ml) <= 0:
            continue
        previous = catalog[int(row.prev_recipe_id)]
        target = catalog[int(row.recipe_id)]
        target_ml = sum(target.ml.values())
        truth = float(row.carry_ml) / (target_ml + float(row.carry_ml))

        manifest_estimate = estimate_carryover(
            (float(row.r), float(row.g), float(row.b)),
            previous,
            target,
            config=config,
        )
        manifest_errors.append(abs(manifest_estimate.fraction_hat - truth))

        filename = full_frames.loc[int(row.vial), "filename"]
        image = cv2.imread(str(ROOT / "synthetic" / "vial_fill" / "images" / filename))
        if image is None:
            raise RuntimeError(f"could not read {filename}")
        observed = extract_vial_features(image).rgb_median
        render_estimate = estimate_carryover(observed, previous, target, config=config)
        render_errors.append(abs(render_estimate.fraction_hat - truth))
        render_fit.append(render_estimate.fit_error)

    return {
        "evaluated_contaminated_vials": len(manifest_errors),
        "manifest_fraction_mae": float(np.mean(manifest_errors)),
        "manifest_fraction_median_ae": float(np.median(manifest_errors)),
        "rendered_fraction_mae": float(np.mean(render_errors)),
        "rendered_fraction_median_ae": float(np.median(render_errors)),
        "rendered_fit_delta_e_median": float(np.median(render_fit)),
        "validation_note": (
            "Manifest recovery is an internal software test; rendered recovery tests twin appearance, "
            "not physical CSI carryover accuracy."
        ),
    }


def _run5_schedule() -> dict:
    labels = vial_labels(ROOT / "data")
    recipes = {recipe.recipe_id: recipe for _, recipe, _, _ in labels}
    submitted = list(recipes)
    matrix = build_transition_matrix(recipes.values())
    exact = optimize_sequence(submitted, matrix, worst_transition_weight=0.5)
    greedy = greedy_sequence(submitted, matrix, worst_transition_weight=0.5)
    return {
        "submitted": submitted,
        "suggested": [batch.recipe_id for batch in exact.suggested],
        "submitted_cost": exact.submitted_cost,
        "suggested_cost": exact.suggested_cost,
        "predicted_relative_reduction": exact.relative_reduction,
        "submitted_transition_sum": exact.submitted_transition_sum,
        "suggested_transition_sum": exact.suggested_transition_sum,
        "transition_sum_reduction": exact.transition_sum_reduction,
        "submitted_worst_transition": exact.submitted_worst_transition,
        "suggested_worst_transition": exact.suggested_worst_transition,
        "worst_transition_reduction": exact.worst_transition_reduction,
        "greedy": [batch.recipe_id for batch in greedy.suggested],
        "greedy_cost": greedy.suggested_cost,
        "fixed_start_recipe_id": exact.fixed_start.recipe_id,
        "cost_note": "Relative model score under assumed 2 mL residual; not measured waste.",
    }


def _run5_observed_ranking() -> dict:
    """Exploratory ranking: first vial versus later vials in each block."""
    labels = vial_labels(ROOT / "data")
    video = ROOT / "data" / "vial_fill" / "videos" / "vial_fill_video_5.mp4"
    cap = cv2.VideoCapture(str(video))
    try:
        colors = {vial: _measure_video_end(cap, end_s) for vial, _, _, end_s in labels}
    finally:
        cap.release()

    recipes = {recipe.recipe_id: recipe for _, recipe, _, _ in labels}
    blocks = {
        recipe_id: [
            vial for vial, recipe, _, _ in labels if recipe.recipe_id == recipe_id
        ]
        for recipe_id in recipes
    }
    matrix = build_transition_matrix(recipes.values())
    rows = []
    order = list(recipes)
    for previous_id, target_id in pairwise(order):
        vials = blocks[target_id]
        later_reference = tuple(np.median([colors[vial] for vial in vials[1:]], axis=0))
        rows.append(
            {
                "from": previous_id,
                "to": target_id,
                "predicted_risk": matrix.value(previous_id, target_id),
                "observed_first_vial_delta_e": delta_e(
                    colors[vials[0]], later_reference
                ),
            }
        )
    table = pd.DataFrame(rows)
    spearman = table.predicted_risk.rank().corr(
        table.observed_first_vial_delta_e.rank()
    )
    return {
        "transitions": rows,
        "spearman_rank_correlation": float(spearman),
        "validation_note": (
            "Exploratory only: later vials are treated as the clean reference, and each directed "
            "transition was observed once."
        ),
    }


def _sensitivity() -> dict:
    labels = vial_labels(ROOT / "data")
    recipes = {recipe.recipe_id: recipe for _, recipe, _, _ in labels}
    submitted = list(recipes)
    report = analyze_sensitivity(recipes.values(), submitted)
    return {
        "scenario_count": len(report.outcomes),
        "improved_scenarios": report.improved_scenarios,
        "median_relative_reduction": report.median_reduction,
        "min_relative_reduction": report.min_reduction,
        "max_relative_reduction": report.max_reduction,
        "unique_recommended_orders": report.unique_orders,
        "most_common_order": report.most_common_order,
        "most_common_order_count": report.most_common_order_count,
        "original_transition_frequency": {
            f"{previous}->{target}": count
            for (
                previous,
                target,
            ), count in report.original_transition_frequency.items()
        },
        "scenarios": [
            {
                "name": outcome.scenario.name,
                "suggested": outcome.suggested,
                "relative_reduction": outcome.relative_reduction,
                "worst_transition_reduction": outcome.worst_reduction,
            }
            for outcome in report.outcomes
        ],
        "validation_note": (
            "Sensitivity analysis over hypothetical holdup, decay and residual-source assumptions; "
            "not physical line validation."
        ),
    }


def main() -> None:
    print(
        json.dumps(
            {
                "synthetic_recovery": _synthetic_recovery(),
                "run5_schedule": _run5_schedule(),
                "run5_observed_ranking": _run5_observed_ranking(),
                "sensitivity": _sensitivity(),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
